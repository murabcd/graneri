import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const skillSources = [
	["documents", "artifact-documents"],
	["spreadsheets", "artifact-spreadsheets"],
	["presentations", "artifact-presentations"],
	["pdf", "artifact-pdf"],
];

const parseSkill = (content, expectedName, sourceUrl) => {
	const match =
		/^---\nname: ([^\n]+)\ndescription: ([^\n]+)\n---\n\n([\s\S]+)\n$/u.exec(
			content,
		);
	if (!match) {
		throw new Error(
			`Invalid artifact skill structure: ${fileURLToPath(sourceUrl)}`,
		);
	}
	const [, name, description, instructions] = match;
	if (name !== expectedName) {
		throw new Error(
			`Expected artifact skill ${expectedName}, received ${name ?? "none"}.`,
		);
	}
	if (!description || !instructions.trim()) {
		throw new Error(`Artifact skill ${name} must not be empty.`);
	}
	return instructions;
};

const skills = {};
for (const [id, name] of skillSources) {
	const sourceUrl = new URL(`../skills/${name}/SKILL.md`, import.meta.url);
	const content = await readFile(sourceUrl, "utf8");
	skills[id] = parseSkill(content, name, sourceUrl);
}

const outputUrl = new URL(
	"../src/artifact-authoring-skills.generated.mjs",
	import.meta.url,
);
const serialized = `// biome-ignore-all format: Generated from canonical SKILL.md files.\n// Generated by scripts/generate-artifact-authoring-skills.mjs.\nexport const ARTIFACT_AUTHORING_SKILLS = Object.freeze(${JSON.stringify(skills, null, "\t")});\n`;

if (process.argv.includes("--check")) {
	const current = await readFile(outputUrl, "utf8").catch(() => "");
	if (current !== serialized) {
		throw new Error(
			`Artifact authoring skills are stale. Run: node ${fileURLToPath(import.meta.url)}`,
		);
	}
} else {
	await writeFile(outputUrl, serialized, "utf8");
}
